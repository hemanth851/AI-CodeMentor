from typing import Optional, List, Dict, Any, Union
from pydantic import BaseModel, Field, field_validator
from app.models.analysis import (
    SUPPORTED_LANGUAGES,
    SUPPORTED_LEVELS,
    MAX_CODE_SIZE_BYTES,
)

# Supported Quiz Categories
SUPPORTED_QUIZ_CATEGORIES = [
    "Program purpose and overall understanding",
    "Variables and data types",
    "Operators and expressions",
    "Conditional statements",
    "Loops and iteration",
    "Functions and parameters",
    "Return values",
    "Lists, arrays, strings, and data structures",
    "Recursion",
    "Algorithm execution and tracing",
    "Output prediction",
    "Error identification and debugging",
    "Time and space complexity",
    "Code structure and control flow",
    "Language-specific concepts",
    "Edge cases and boundary conditions",
]


class QuizQuestionLLM(BaseModel):
    """Internal model for a single question generated by Gemini."""
    question: str = Field(..., description="The multiple choice question text grounded strictly in the code")
    options: List[str] = Field(..., description="Exactly 4 distinct plausible options")
    correct_answer_index: int = Field(..., description="0-indexed position (0, 1, 2, or 3) of the single correct answer")
    explanation: str = Field(..., description="Clear explanation of why the correct option is right and others are incorrect")
    category: str = Field(..., description="Relevant concept/category from the code")
    difficulty: str = Field(..., description="Difficulty level (Beginner, Intermediate, Advanced)")
    code_evidence: Optional[str] = Field(default=None, description="Direct code evidence or line reference")
    learning_takeaway: Optional[str] = Field(default=None, description="Short pedagogical key takeaway")


class QuizLLMResponse(BaseModel):
    """Schema for Gemini LLM structured response."""
    questions: List[QuizQuestionLLM] = Field(
        ...,
        description="Exactly 5 questions assessing concepts actually present in the source code",
    )


class QuizQuestionPublic(BaseModel):
    """Question sent to the frontend before submission (correct answer & explanation stripped)."""
    id: int = Field(..., description="1-indexed question identifier")
    question: str = Field(..., description="Question text")
    options: List[str] = Field(..., description="List of 4 multiple-choice options")
    category: str = Field(..., description="Concept assessed by this question")
    difficulty: str = Field(..., description="Difficulty level")


class QuizGenerateRequest(BaseModel):
    """Payload for generating a dynamic assessment quiz."""
    code: str = Field(
        ...,
        description="Source code to assess",
        min_length=1,
    )
    language: str = Field(
        default="Python",
        description="Programming language of the code",
    )
    learning_level: str = Field(
        default="Beginner",
        description="Target educational depth (Beginner, Intermediate, Advanced)",
    )
    analysis: Optional[Union[Dict[str, Any], Any]] = Field(
        default=None,
        description="Existing structured explanation from Step 5",
    )
    static_analysis: Optional[Union[Dict[str, Any], Any]] = Field(
        default=None,
        description="Lightweight static analysis facts from Step 4",
    )

    @field_validator("code")
    @classmethod
    def validate_code(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Code must not be empty.")
        if len(v.encode("utf-8")) > MAX_CODE_SIZE_BYTES:
            raise ValueError(f"Code exceeds maximum permitted size of {MAX_CODE_SIZE_BYTES // 1024} KB.")
        return v

    @field_validator("learning_level")
    @classmethod
    def validate_learning_level(cls, v: str) -> str:
        for valid_level in SUPPORTED_LEVELS:
            if v.strip().lower() == valid_level.lower():
                return valid_level
        raise ValueError(
            f"Invalid learning level '{v}'. Must be one of: {', '.join(SUPPORTED_LEVELS)}"
        )


class QuizGenerateResponse(BaseModel):
    """Response returned when generating a quiz."""
    success: bool = Field(default=True, description="Whether quiz generation succeeded")
    quiz_id: str = Field(..., description="Unique session identifier for this quiz")
    quiz_token: str = Field(..., description="Secure signed token concealing correct answers until submission")
    total_questions: int = Field(default=5, description="Total number of questions")
    questions: List[QuizQuestionPublic] = Field(default_factory=list, description="Public questions without answers")
    error: Optional[str] = Field(default=None, description="User-safe error explanation if failed")


class QuizSubmitRequest(BaseModel):
    """Payload for scoring answers."""
    quiz_id: str = Field(..., description="Quiz identifier")
    quiz_token: str = Field(..., description="Secure token from generate step")
    answers: Dict[str, int] = Field(
        ...,
        description="Map of question_id (stringified int '1'..'5') to selected option index (0..3)",
    )


class QuestionReview(BaseModel):
    """Detailed review for a single question after submission."""
    question_id: int = Field(..., description="Question number")
    question: str = Field(..., description="Question text")
    options: List[str] = Field(..., description="The 4 options")
    selected_index: Optional[int] = Field(..., description="Index user selected, or null if unanswered")
    correct_index: int = Field(..., description="Actual correct option index (0..3)")
    is_correct: bool = Field(..., description="Whether user's answer matched")
    explanation: str = Field(..., description="Pedagogical explanation of the answer")
    category: str = Field(..., description="Concept assessed")
    difficulty: Optional[str] = Field(default=None, description="Question difficulty")
    code_evidence: Optional[str] = Field(default=None, description="Direct code evidence or line reference")
    learning_takeaway: Optional[str] = Field(default=None, description="Short pedagogical key takeaway")


class QuizSubmitResponse(BaseModel):
    """Deterministic score and feedback revealed upon submission."""
    success: bool = Field(default=True, description="Whether scoring succeeded")
    score: int = Field(..., description="Number of correct answers (0..5)")
    total: int = Field(default=5, description="Total number of questions")
    percentage: float = Field(..., description="Percentage score (0.0 to 100.0)")
    review: List[QuestionReview] = Field(default_factory=list, description="Question-by-question review")
    feedback: str = Field(..., description="Encouraging summary feedback based on score")
    error: Optional[str] = Field(default=None, description="User-safe error description if failed")
